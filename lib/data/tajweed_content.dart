import 'quran.dart';

class TExample {
  final String text;
  final String note;
  final AyahRef? ref;
  const TExample(this.text, this.note, [this.ref]);
}

class TLesson {
  final String title;
  final String body;
  final List<TExample> examples;
  const TLesson(this.title, this.body, [this.examples = const []]);
}

class TQuestion {
  final String q;
  final List<String> options;
  final int answer;
  final String why;
  const TQuestion(this.q, this.options, this.answer, this.why);
}

class TLevel {
  final String title;
  final String sub;
  final List<TLesson> lessons;
  final List<TQuestion> quiz;
  const TLevel(this.title, this.sub, this.lessons, this.quiz);
}

